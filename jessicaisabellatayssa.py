# Dada a seguinte lista de convidados: convidados = ["Ana", "Bruno", "Carlos", "Diana"].
# Usa um ciclo for para imprimir uma mensagem personalizada para cada um.
# Exemplo de saída: "Olá, Ana! Bem-vinda à aula de programação."


